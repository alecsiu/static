#!/usr/bin/env python3
"""Regenerate index.html from the *.html pages in this directory plus external.json.

Each page needs a <title> and <meta name="description">. No dependencies, no network.
"""
import json
import sys
from html import escape
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent


class Head(HTMLParser):
    def __init__(self):
        super().__init__()
        self.title, self.description, self._in_title = "", "", False

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "title":
            self._in_title = True
        elif tag == "meta" and a.get("name") == "description":
            self.description = (a.get("content") or "").strip()

    def handle_endtag(self, tag):
        if tag == "title":
            self._in_title = False

    def handle_data(self, data):
        if self._in_title:
            self.title += data


def accent(key):
    h = 0
    for ch in key:
        h = (h * 31 + ord(ch)) % 360
    return f"hsl({h} 55% 48%)"


def collect():
    items, problems = [], []
    for p in sorted(ROOT.glob("*.html")):
        if p.name == "index.html":
            continue
        head = Head()
        head.feed(p.read_text(encoding="utf-8"))
        title = head.title.strip() or p.stem
        if not head.title.strip():
            problems.append(f"{p.name}: missing <title>")
        if not head.description:
            problems.append(f'{p.name}: missing <meta name="description">')
        items.append({"title": title, "href": p.name, "description": head.description})
    ext = ROOT / "external.json"
    if ext.exists():
        items += json.loads(ext.read_text(encoding="utf-8"))
    for i in items:
        i["accent"] = accent(i["href"])
    return sorted(items, key=lambda i: i["title"].lower()), problems


CSS = """
    *, *::before, *::after { box-sizing: border-box; margin: 0; padding: 0; }
    :root { --bg:#fff; --surface:#f5f5f7; --surface-hover:#ebebed; --border:#d2d2d7; --text:#1d1d1f; --muted:#6e6e73; }
    @media (prefers-color-scheme: dark) {
      :root { --bg:#0f1117; --surface:#1a1d27; --surface-hover:#22263a; --border:#2a2e42; --text:#e8eaf2; --muted:#7c8aaa; }
    }
    body { background:var(--bg); color:var(--text); font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",system-ui,sans-serif; min-height:100vh; padding:3rem 1.5rem; line-height:1.6; }
    .container { max-width:680px; margin:0 auto; }
    h1 { font-size:1.75rem; font-weight:700; letter-spacing:-0.02em; margin-bottom:2.5rem; }
    .list { display:flex; flex-direction:column; gap:.75rem; }
    a.card { display:block; background:var(--surface); border:1px solid var(--border); border-left:4px solid var(--card-accent); border-radius:12px; padding:1.25rem 1.5rem; text-decoration:none; transition:background .15s, transform .1s; }
    a.card:hover { background:var(--surface-hover); transform:translateX(2px); }
    .card-title { font-size:1rem; font-weight:600; color:var(--card-accent); margin-bottom:.25rem; }
    .card-desc { font-size:.875rem; color:var(--muted); }
"""


def render(items):
    cards = "\n".join(
        f'      <a class="card" href="{escape(i["href"])}" style="--card-accent: {i["accent"]};">\n'
        f'        <div class="card-title">{escape(i["title"])}</div>\n'
        f'        <div class="card-desc">{escape(i["description"])}</div>\n'
        f"      </a>"
        for i in items
    )
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Tools</title>
  <!-- Generated by generate_index.py. Do not edit by hand. -->
  <style>{CSS}  </style>
</head>
<body>
  <div class="container">
    <h1>Tools</h1>
    <div class="list">
{cards}
    </div>
  </div>
</body>
</html>
"""


if __name__ == "__main__":
    items, problems = collect()
    for msg in problems:
        print(f"error: {msg}", file=sys.stderr)
    if problems:
        sys.exit(1)
    (ROOT / "index.html").write_text(render(items), encoding="utf-8")
    print(f"Wrote index.html with {len(items)} entries")
